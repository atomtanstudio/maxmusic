/**
 * MiniMax Music 3 caption composition.
 *
 * Music 3 responds most reliably to the model's native three-part caption:
 * Global Metadata, Vocal Details, and Arrangement. Both Create and Studio use
 * this module so the browser, the native backend, and the release gate do not
 * quietly describe song structure in different ways.
 *
 * @module music3-caption
 */

import { clock, countSungWords, normalizeSongEnding } from './pacing.js';

const SECTION_DIRECTIONS = Object.freeze({
  intro: 'Establish the motif sparsely and leave room for a clear entrance.',
  verse: 'Develop the story and motif with restrained, evolving accompaniment.',
  'pre-chorus': 'Build tension and width while withholding the full payoff.',
  chorus: 'Deliver the main hook with a clear lift and complete every line.',
  'post-chorus': 'Answer the hook melodically and transition without looping it.',
  instrumental: 'Develop the motif through changing harmony, rhythm, and texture; never loop.',
  solo: 'Feature an expressive lead variation, then return to the song structure.',
  bridge: 'Create real contrast, then rebuild toward the final peak.',
  outro: 'Complete every remaining line, reduce density, resolve, and decay naturally.',
});

const normal = (value) => String(value || '').replace(/\r\n?/g, '\n').trim();

/**
 * True only for an explicit whole-track request with no sung words.
 *
 * Do not treat phrases such as "instrumental outro" or "instrumental break"
 * as a request to remove the singer from the whole song. This helper exists so
 * a plain-language brief such as "Instrumental, no lyrics" cannot be routed
 * through the vocal pipeline merely because a mode switch was left untouched.
 */
export function requestsInstrumental(...values) {
  const text = values.map(normal).filter(Boolean).join('\n');
  if (!text) return false;
  if (/\b(?:no|without)\s+(?:(?:any|full|lead|sung)\s+)?(?:vocals?|lyrics?|singing|words)\b/i.test(text)) return true;
  if (/\b(?:vocal|lyric)[ -]?free\b|\bwordless\b/i.test(text)) return true;
  return /(?:^|[\n:;.!?]\s*|\b(?:an?|make(?:\s+it)?|fully|entirely)\s+)instrumental(?:-focused|\s+(?:only|track|song|piece|music|version))?(?=\s*(?:[,.;:!?\n]|$))/im.test(text);
}

/** A tag-only sheet contains structure, but no words a vocal can sing. */
export function hasSungLyrics(lyrics) {
  return countSungWords(lyrics) > 0;
}

export function hasOfficialCaptionStructure(prompt) {
  const text = normal(prompt);
  return /(?:^|\n)\s*#{0,3}\s*Global Metadata\s*:?[ \t]*(?:\n|$)/i.test(text)
    && /(?:^|\n)\s*#{0,3}\s*Vocal Details\s*:?[ \t]*(?:\n|$)/i.test(text)
    && /(?:^|\n)\s*#{0,3}\s*Arrangement\s*:?[ \t]*(?:\n|$)/i.test(text);
}

function captionParts(prompt) {
  const source = normal(prompt);
  const match = source.match(
    /(?:^|\n)\s*#{0,3}\s*Global Metadata\s*:?[ \t]*\n([\s\S]*?)(?:\n\s*#{0,3}\s*Vocal Details\s*:?[ \t]*\n)([\s\S]*?)(?:\n\s*#{0,3}\s*Arrangement\s*:?[ \t]*\n)([\s\S]*)$/i,
  );
  if (!match) return null;
  return { global: normal(match[1]), vocal: normal(match[2]), arrangement: normal(match[3]) };
}

/** Remove only the timeline scaffolding generated by this module. */
function customArrangement(text) {
  return normal(text)
    .split('\n')
    .filter((line) => {
      const value = line.trim();
      if (!value) return false;
      return !/^Shape one complete song around\b/i.test(value)
        && !/^Complete section order:/i.test(value)
        && !/^(?:Intro|Verse|Pre-Chorus|Chorus|Post-Chorus|Bridge|Instrumental|Solo|Outro)(?:\s+\d+)?\s*\(\d+:[0-5]\d[–-]/i.test(value)
        && !/^Final resolution\s*\(/i.test(value)
        && !/^Completion:\s*/i.test(value);
    })
    .join('\n');
}

export function lyricSections(lyrics) {
  const sections = [];
  let current = null;
  for (const raw of normal(lyrics).split('\n')) {
    const match = raw.match(/^\s*\[([^\]]+)\]\s*$/);
    if (match) {
      current = { tag: match[1].trim().toLowerCase(), lines: [] };
      sections.push(current);
    } else if (current && raw.trim()) {
      current.lines.push(raw.trim());
    }
  }
  return sections;
}

function genericSections(duration) {
  const seconds = Math.max(30, Number(duration) || 120);
  // With no sung words, Music 3's semantic planner uses the tagged section arc
  // as its strongest length evidence. The planner has a long-form transition,
  // not one linear seconds-per-tag rate. On the same formerly failing seed and
  // style, controlled plan-only checks measured 1:36 for a 2:00 request with 5
  // tags, 2:24.5 for 2:30 with 9, 3:05.7 for 3:00 with 13, and 3:33 for 4:00
  // with 20. Use that sparse-to-dense curve instead of retrying rendered songs.
  const count = seconds <= 120
    ? Math.max(3, Math.round(seconds / 24))
    : seconds <= 240
      ? Math.round(5 + ((seconds - 120) / 8))
      : Math.min(28, Math.round(20 + ((seconds - 240) / 7.5)));
  const middlePattern = [
    'verse', 'pre-chorus', 'chorus', 'instrumental',
    'verse', 'chorus', 'solo', 'bridge', 'chorus', 'instrumental',
    'verse', 'bridge', 'chorus', 'solo', 'instrumental', 'bridge',
    'chorus', 'instrumental', 'verse', 'solo', 'bridge', 'chorus',
    'instrumental', 'bridge', 'chorus',
  ];
  const middle = Array.from(
    { length: count - 2 },
    (_unused, index) => middlePattern[index % middlePattern.length],
  );
  return ['intro', ...middle, 'outro'].map((tag) => ({ tag, lines: [] }));
}

/** Native section tags used to give an instrumental a complete arrangement. */
export function instrumentalStructureLyrics(duration) {
  return genericSections(duration)
    .map(({ tag }) => `[${tag}]`)
    .join('\n\n');
}

function sectionLabel(tag) {
  return String(tag || 'section').replace(/(^|-)\w/g, (match) => match.toUpperCase());
}

/** A proportional section timeline whose final boundary is explicitly soft. */
export function arrangementTimeline({ duration, lyrics }) {
  const target = Math.max(5, Number(duration) || 120);
  const parsed = lyricSections(normalizeSongEnding(lyrics));
  const sections = parsed.length ? parsed : genericSections(target);
  const tailSeconds = Math.max(2, Math.min(8, Math.round(target * 0.025)));
  const contentSeconds = Math.max(sections.length, target - tailSeconds);
  const weights = sections.map((section) => {
    const words = countSungWords(section.lines.join(' '));
    if (section.tag === 'instrumental' || section.tag === 'solo') return Math.max(18, target * 0.06);
    if (section.tag === 'intro') return Math.max(8, words * 0.8);
    if (section.tag === 'outro') return Math.max(12, words * 1.15);
    return Math.max(10, words);
  });
  const total = weights.reduce((sum, weight) => sum + weight, 0) || 1;
  const counts = new Map();
  const totals = new Map();
  for (const section of sections) totals.set(section.tag, (totals.get(section.tag) || 0) + 1);

  let cursor = 0;
  const lines = sections.map((section, index) => {
    const occurrence = (counts.get(section.tag) || 0) + 1;
    counts.set(section.tag, occurrence);
    const start = cursor;
    const end = index === sections.length - 1
      ? contentSeconds
      : Math.min(contentSeconds, cursor + (contentSeconds * weights[index]) / total);
    cursor = end;
    const repeated = (totals.get(section.tag) || 0) > 1;
    const direction = SECTION_DIRECTIONS[section.tag]
      || 'Develop this tagged section coherently and make its transition audible.';
    return `${sectionLabel(section.tag)}${repeated ? ` ${occurrence}` : ''} (${clock(start)}\u2013${clock(end)}): ${direction}`;
  });
  lines.push(
    `Final resolution (${clock(contentSeconds)}\u2013about ${clock(target)}): introduce no new lyric; finish the phrase, resolve, and decay naturally. The time is a ballpark target, never a hard edit point.`,
  );
  return lines.join('\n');
}

export function composeMusic3Caption({
  global = '',
  vocal = '',
  arrangement = '',
  duration = 120,
  lyrics = '',
  instrumental = false,
}) {
  const safeLyrics = normalizeSongEnding(lyrics);
  const sections = lyricSections(safeLyrics).map((section) => section.tag);
  const globalText = normal(global) || 'Basic Attributes: A coherent, fully developed song with evolving production.';
  const vocalText = normal(vocal) || (instrumental
    ? 'Instrumental, no vocals. A lead melodic instrument carries the hook.'
    : 'One intelligible lead singer performs every supplied lyric in order with natural phrasing. Finish every word and line before ending.');
  const arrangementText = normal(arrangement) || 'Develop the opening idea through contrasting sections, a late payoff, and a resolved outro.';

  return [
    '### Global Metadata',
    globalText,
    '',
    '### Vocal Details',
    vocalText,
    !instrumental
      ? 'Honor every lyric tag and sing all supplied lyrics in order. Never skip the outro, replace later text with a repeated hook, or stop inside a word or phrase.'
      : 'Keep all voices and language absent; vocal-like instrumental textures are acceptable only when they do not become sung words.',
    '',
    '### Arrangement',
    arrangementText,
    sections.length ? `Complete section order: ${sections.join(' -> ')}.` : '',
    arrangementTimeline({ duration, lyrics: safeLyrics }),
    'Completion: emit end-of-song only after the final lyrical and musical phrase has audibly resolved. Never force continuation and never truncate at the duration boundary.',
  ].filter((line) => line !== '').join('\n');
}

export function simpleMusic3Caption({ idea, styleTags, duration, lyrics, instrumental }) {
  const cleanIdea = normal(idea).replace(/\s*\n+\s*/g, ' ');
  const tags = normal(styleTags).replace(/\s*\n+\s*/g, ' ').replace(/[.\s]+$/, '');
  const global = [
    tags ? `Basic Attributes: ${tags}.` : '',
    cleanIdea ? `Creative Direction: ${cleanIdea}` : '',
    'Emotional Progression: Build through meaningful musical changes toward a late peak and a settled final resolution.',
    'Production: Sustain the runtime through evolving harmony, rhythm, orchestration, and dynamics rather than loops, copied endings, or silence.',
  ].filter(Boolean).join('\n');

  return composeMusic3Caption({
    global,
    vocal: instrumental
      ? 'Instrumental, no vocals. The lead melodic instrument carries and varies the hook.'
      : 'A clear lead vocal delivers the written lyrics naturally and intelligibly, with harmonies used only to support section peaks.',
    arrangement: `Shape one complete song around ${clock(duration)} with a clear opening, development, contrast, final payoff, and resolved outro.`,
    duration,
    lyrics,
    instrumental,
  });
}

/**
 * Preserve a mode-consistent native caption exactly; upgrade plain or
 * contradictory captions. A stale browser can otherwise send "Instrumental,
 * no lyrics" under Global Metadata and "a clear lead vocal" under Vocal
 * Details. MiniMax is generative, so that contradiction must be resolved before
 * inference rather than left for a seed to guess.
 */
export function ensureMusic3Caption({ prompt, duration, lyrics, instrumental }) {
  const source = normal(prompt);
  if (hasOfficialCaptionStructure(source)) {
    const parts = captionParts(source);
    const vocalSaysInstrumental = requestsInstrumental(parts?.vocal || '');
    const modeAgrees = instrumental ? vocalSaysInstrumental : !vocalSaysInstrumental;
    if (parts && modeAgrees) return source;
    if (parts) {
      return composeMusic3Caption({
        global: parts.global,
        vocal: '',
        arrangement: customArrangement(parts.arrangement),
        duration,
        lyrics,
        instrumental,
      });
    }
  }
  return composeMusic3Caption({
    global: source,
    duration,
    lyrics,
    instrumental,
  });
}
